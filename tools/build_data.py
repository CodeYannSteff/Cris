#!/usr/bin/env python3
"""Convert the paintings into packed ASCII cell grids (R,G,B,A per cell).

Output: js/data.js — consumed by the pure HTML/JS/CSS experience.
Cell aspect assumption: cellW = 0.6 * cellH (enforced at runtime).
"""

import base64
import json
import os

from PIL import Image, ImageEnhance, ImageFilter

LANCZOS = Image.Resampling.LANCZOS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "js", "data.js")

ROWS = 200
CELL_ASPECT = 0.6
GAP_CELLS = 48
EDGE_FADE_X = 16
EDGE_FADE_Y = 12

PAINTINGS = [
    {
        "id": "alley",
        "file": "Die-bedeckte-Allee.jpg",
    },
    {
        "id": "sentier",
        "file": "Renoir_-_Sentier_dans_le_bois,_circa_1874-1877.jpg",
    },
]


def smoothstep(a, b, x):
    if a == b:
        return 0.0 if x < a else 1.0
    t = max(0.0, min(1.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)


def make_fade(cols, rows):
    """Soft alpha mask: dissolve painting edges into the void."""
    a = []
    for y in range(rows):
        for x in range(cols):
            fx = smoothstep(0, EDGE_FADE_X, x) * smoothstep(
                0, EDGE_FADE_X, cols - 1 - x
            )
            fy = smoothstep(0, EDGE_FADE_Y, y) * smoothstep(
                0, EDGE_FADE_Y, rows - 1 - y
            )
            a.append(fx * fy)
    return a


def stretch_luma(luma, lo=2.0, hi=98.0):
    """Percentile stretch + gentle S-curve so glyphs span the full ramp."""
    px = sorted(luma)
    n = len(px)
    p_lo = px[min(n - 1, int(n * lo / 100))]
    p_hi = px[min(n - 1, int(n * hi / 100))]
    rng = max(1, p_hi - p_lo)
    out = []
    for v in luma:
        t = max(0.0, min(1.0, (v - p_lo) / rng))
        # soft filmic S-curve
        t = t * t * (3 - 2 * t) * 0.85 + t * 0.15
        out.append(t)
    return out


def process(path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    cols = max(1, round(ROWS * (w / h) / CELL_ASPECT))

    # Color: high-quality downsample, slight saturation lift for screen punch
    small = im.resize((cols, ROWS), LANCZOS)
    small = ImageEnhance.Color(small).enhance(1.12)
    small = ImageEnhance.Contrast(small).enhance(1.06)
    # Tiny blur kills JPEG noise that would flicker in the glyph ramp
    small = small.filter(ImageFilter.GaussianBlur(0.6))

    # Luminance from a slightly larger resample (sharper detail for glyphs)
    lum_im = im.resize((cols, ROWS), LANCZOS).convert("L")
    lum_im = ImageEnhance.Contrast(lum_im).enhance(1.15)
    lum = lum_im.tobytes()
    luma_t = stretch_luma(lum)

    rgb = small.tobytes()
    fade = make_fade(cols, ROWS)

    buf = bytearray(cols * ROWS * 4)
    for i in range(cols * ROWS):
        f = fade[i]
        if f <= 0:
            continue
        j = i * 4
        k = i * 3
        buf[j] = rgb[k]
        buf[j + 1] = rgb[k + 1]
        buf[j + 2] = rgb[k + 2]
        buf[j + 3] = int(round(255 * f))

    return cols, luma_t, bytes(buf)


def main():
    out = {
        "rows": ROWS,
        "cellAspect": CELL_ASPECT,
        "gap": GAP_CELLS,
        "scenes": {},
    }
    for p in PAINTINGS:
        cols, luma, raw = process(os.path.join(ROOT, p["file"]))
        luma_bytes = bytes(max(0, min(255, int(round(v * 255)))) for v in luma)
        out["scenes"][p["id"]] = {
            "cols": cols,
            "rows": ROWS,
            "rgb": base64.b64encode(raw).decode("ascii"),
            "lum": base64.b64encode(luma_bytes).decode("ascii"),
        }
        print(f"{p['id']}: {cols}x{ROWS}  ({len(raw)} bytes rgb)")

    js = (
        "// generated by tools/build_data.py — do not edit\n"
        "window.ASCII_DATA = " + json.dumps(out) + ";\n"
    )
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(js)
    print(f"wrote {OUT} ({len(js)} bytes)")


if __name__ == "__main__":
    main()
